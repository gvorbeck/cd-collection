#!/usr/bin/env node
/* ============================================================
   check-shell-assets.js — does the offline shell list everything?
   ------------------------------------------------------------
   sw.js precaches SHELL_ASSETS by hand, one path per line,
   because there is no build step to generate the list. A
   hand-kept list drifts, and it has: icon-maskable-512.png was
   declared in manifest.webmanifest and precached nowhere. The
   comment above the module block in sw.js already spells out the
   worse version — "a page names only its entry point, but the
   browser resolves imports at fetch time, so an unlisted module
   is a network request the offline shell can't answer."

   Nothing catches that drift on its own. The site works perfectly
   online whether the list is right or wrong, so the only symptom
   is a page that white-screens with no signal — in the record
   shop, which is both the case the offline support exists for and
   the one place nobody can open a console. So it is checked here,
   and in CI before anything deploys.

   What it asserts:

     - every .js under js/ is named in SHELL_ASSETS
     - every icons[].src in manifest.webmanifest is named there too
     - every path SHELL_ASSETS names exists in the tree
     - every module reachable by following imports out of each
       page's entry script is precached, and is itself in the tree
     - every non-module <script src> a page loads from this repo is
       precached too

   Run it:

       node scripts/check-shell-assets.js

   Exit code 1 and a list of what drifted, or 0 and a count.

   Node's standard library only, and CommonJS, to match
   make-icons.js and snapshot.js — the site has no package.json,
   and adding one with {"type":"module"} would break all three.
   ============================================================ */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SW_JS = path.join(ROOT, 'sw.js');
const MANIFEST = path.join(ROOT, 'manifest.webmanifest');
const JS_DIR = path.join(ROOT, 'js');

/* The one SHELL_ASSETS entry allowed to be absent from the tree.

   data/collection.csv is generated by scripts/snapshot.js from the live sheet,
   so a checkout where the script has never been run legitimately hasn't got
   it. sw.js says as much at the entry itself, and install() adds assets one by
   one specifically so the miss costs nothing. Failing the build over a file
   this check cannot produce would turn a documented, tolerated absence into a
   red build — the definition of crying wolf. It is reported as a note instead,
   because an offline first launch really is worse without it. */
const GENERATED_ASSETS = new Set(['data/collection.csv']);

/* ---------- What sw.js says it precaches ---------- */

/**
 * Pull the SHELL_ASSETS array out of sw.js, a line at a time.
 *
 * Line by line rather than a sweep for quoted strings over the whole array,
 * because the array is half prose and one of those comments ends "…an unlisted
 * module is a network request the offline shell can't answer" — a lone
 * apostrophe that /'([^']*)'/ reads as the opening quote of an asset path, and
 * then runs to the next real entry. Every actual entry is a single-quoted
 * string alone on its line; anything else in there is English.
 */
function readShellAssets() {
  const src = fs.readFileSync(SW_JS, 'utf8');
  const block = src.match(/const SHELL_ASSETS = \[([\s\S]*?)\n\];/);
  if (!block) throw new Error('Could not find SHELL_ASSETS in sw.js — has it been reshaped?');

  const assets = [];
  for (const line of block[1].split('\n')) {
    const entry = line.trim().match(/^'([^']*)',?$/);
    if (entry) assets.push(entry[1]);
  }
  // A silent zero here would pass every check below with flying colours, which
  // is the one result this script must never produce by accident.
  if (assets.length === 0) {
    throw new Error('SHELL_ASSETS parsed as empty — has the list stopped being one quoted path per line?');
  }
  return assets;
}

function readManifestIcons() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  return (manifest.icons || []).map((icon) => icon.src).filter(Boolean);
}

/* ---------- What is actually in the tree ---------- */

// Repo-relative, forward slashes: the form SHELL_ASSETS is written in.
function repoPath(full) {
  return path.relative(ROOT, full).split(path.sep).join('/');
}

/**
 * Every .js file under js/.
 *
 * Recursive, so a module tucked into a subdirectory some day is still checked.
 * Dot-directories are skipped — js/.claude is editor configuration, not code
 * the browser will ever ask for.
 */
function listModules(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...listModules(full));
    else if (entry.name.endsWith('.js')) found.push(repoPath(full));
  }
  return found.sort();
}

// The pages, discovered rather than listed, so a fourth one is covered the day
// it lands instead of the day someone remembers this file exists.
function listPages() {
  return fs.readdirSync(ROOT).filter((name) => name.endsWith('.html')).sort();
}

/* ---------- The import graph ---------- */

/**
 * The static import specifiers in a module.
 *
 * A regex, not a parser, and it holds because of two properties of this
 * codebase worth stating out loud. Every import statement starts at column
 * zero with the word `import` — the multi-line ones included, since their
 * closing `} from '…';` belongs to the statement the match is already inside.
 * And there are no dynamic imports anywhere, so nothing can pull in a module
 * this walk never sees. Should either stop being true, this check goes quiet
 * rather than loud, which is the failure mode to watch for.
 *
 * The optional middle covers `import './x.js';`, the side-effect form with no
 * `from` clause. Nothing uses it today, but a module imported only for what it
 * does on evaluation still has to be precached.
 */
const IMPORT_RE = /^import\b\s*(?:[^;]*?\bfrom\s*)?'([^']+)'/gm;

function importsOf(source) {
  return [...source.matchAll(IMPORT_RE)].map((match) => match[1]);
}

// Every <script src> on a page, split by whether it's a module.
//
// The modules are entry points to walk imports from. The classic ones are
// PapaParse, which imports nothing and so has no graph to follow — but it is
// vendored in this repo now rather than loaded from a CDN, which makes it a
// file that has to be precached like any other. It used to be exempt from this
// check for the good reason that it lived on somebody else's server, and stayed
// exempt after it moved for no reason at all.
function scriptEntries(html) {
  const modules = [];
  const classic = [];
  for (const tag of html.match(/<script\b[^>]*>/gi) || []) {
    const src = tag.match(/\bsrc\s*=\s*["']([^"']+)["']/i);
    if (!src) continue;   // inline script, nothing to fetch
    (/\btype\s*=\s*["']module["']/i.test(tag) ? modules : classic).push(src[1]);
  }
  return { modules, classic };
}

// Resolve a specifier against the file that wrote it, in repo-relative terms:
// index.html's 'js/app.js' lands on js/app.js, and js/app.js's './state.js'
// lands on js/state.js.
function resolveFrom(fromPath, specifier) {
  return path.posix.normalize(path.posix.join(path.posix.dirname(fromPath), specifier));
}

/**
 * Every module reachable from a set of entry points, by following imports.
 *
 * Returns { reachable, broken } — `broken` being specifiers that resolve to a
 * file that isn't there. That is a page broken online as well as off, so it is
 * caught here rather than in somebody's browser console.
 *
 * The seen-set is doing real work even though the graph is acyclic (which
 * test/imports.test.mjs enforces). It's a diamond, not a tree: util.js is
 * imported by nearly everything, and store.js and dom.js by most of the rest.
 * Without the set those subtrees get re-walked once per path into them.
 */
function walkImports(entries) {
  const reachable = new Set();
  const broken = [];
  const queue = [...entries];

  while (queue.length) {
    const file = queue.shift();
    if (reachable.has(file)) continue;
    reachable.add(file);

    const full = path.join(ROOT, file);
    if (!fs.existsSync(full)) continue;   // reported by the caller that queued it

    const source = fs.readFileSync(full, 'utf8');
    for (const specifier of importsOf(source)) {
      // Only a relative specifier names a file in this repo. There are no bare
      // or absolute ones, and an import map would have to arrive before there
      // could be — so anything else is out of this check's reach by design.
      if (!specifier.startsWith('.')) continue;
      const target = resolveFrom(file, specifier);
      if (!fs.existsSync(path.join(ROOT, target))) {
        broken.push(`${file} imports '${specifier}', and ${target} is not in the tree`);
        continue;
      }
      queue.push(target);
    }
  }

  return { reachable, broken };
}

/* ---------- Run the checks ---------- */

// SHELL_ASSETS writes paths bare ('js/app.js'); a page or an import specifier
// may write the same file with a leading './'. Compare on one form so a listing
// that grows a './' one day doesn't read as a missing asset. './' itself is the
// directory index, not a path with a prefix to strip, hence the lookahead.
const normalize = (p) => p.replace(/^\.\/(?=.)/, '');

const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

function main() {
  const listed = readShellAssets();
  const assets = new Set(listed.map(normalize));
  const problems = [];
  const notes = [];

  /* Every module in js/ is precached. */
  const modules = listModules(JS_DIR);
  const unlisted = modules.filter((file) => !assets.has(file));
  if (unlisted.length) {
    problems.push([
      `${plural(unlisted.length, 'module')} under js/ missing from SHELL_ASSETS in sw.js:`,
      ...unlisted.map((file) => `    ${file}`),
      '  offline, the browser asks the network for these and gets nothing back.',
    ].join('\n'));
  }

  /* Every icon the manifest declares is precached. */
  const icons = readManifestIcons();
  const unlistedIcons = icons.map(normalize).filter((src) => !assets.has(src));
  if (unlistedIcons.length) {
    problems.push([
      `${plural(unlistedIcons.length, 'icon')} in manifest.webmanifest missing from SHELL_ASSETS in sw.js:`,
      ...unlistedIcons.map((src) => `    ${src}`),
      '  the install prompt and the home-screen icon are the first things to go.',
    ].join('\n'));
  }

  /* Everything precached is really there. The reverse drift: a file renamed or
     deleted while sw.js kept naming the old path. install() swallows the 404
     per-asset, so this fails silently at runtime too. */
  const absent = [];
  for (const asset of listed) {
    // Absolute URLs are somebody else's server, and './' is the directory
    // index rather than a file — neither is a path in this repo to look for.
    if (/^https?:\/\//i.test(asset) || asset.endsWith('/')) continue;
    const file = normalize(asset);
    if (fs.existsSync(path.join(ROOT, file))) continue;
    if (GENERATED_ASSETS.has(file)) {
      notes.push(`${file} is not in the tree — run \`node scripts/snapshot.js\` and commit it, or a fresh install has no data offline.`);
      continue;
    }
    absent.push(file);
  }
  if (absent.length) {
    problems.push([
      `${plural(absent.length, 'path')} in SHELL_ASSETS that ${absent.length === 1 ? 'is' : 'are'} not in the tree:`,
      ...absent.map((file) => `    ${file}`),
      '  install() tolerates the 404 per-asset, so this goes wrong quietly.',
    ].join('\n'));
  }

  /* The one that needed a graph walk: every module a page can reach. */
  const pages = listPages();
  const entries = [];
  const classic = new Set();
  for (const page of pages) {
    const html = fs.readFileSync(path.join(ROOT, page), 'utf8');
    const { modules, classic: plain } = scriptEntries(html);
    for (const src of modules) entries.push(resolveFrom(page, src));
    // Absolute URLs are somebody else's server to cache or not.
    for (const src of plain) if (!/^https?:\/\//i.test(src)) classic.add(resolveFrom(page, src));
  }
  if (entries.length === 0) {
    throw new Error(`No module <script> found in any of ${pages.join(', ')} — has the markup changed?`);
  }

  /* Classic <script src> tags name repo files too, and a page whose parser is
     missing offline shows an empty shelf rather than a broken one. */
  const unlistedClassic = [...classic].filter((file) => !assets.has(file)).sort();
  if (unlistedClassic.length) {
    problems.push([
      `${plural(unlistedClassic.length, 'script')} loaded by a page but missing from SHELL_ASSETS in sw.js:`,
      ...unlistedClassic.map((file) => `    ${file}`),
      '  not a module, so nothing else 404s with it — the page just quietly loses what it does.',
    ].join('\n'));
  }

  const { reachable, broken } = walkImports(entries);
  const unreachableOffline = [...reachable].filter((file) => !assets.has(file)).sort();
  if (unreachableOffline.length) {
    problems.push([
      `${plural(unreachableOffline.length, 'module')} reachable from a page but missing from SHELL_ASSETS in sw.js:`,
      ...unreachableOffline.map((file) => `    ${file}`),
      '  the page loads, the import 404s, and the whole module graph fails with it.',
    ].join('\n'));
  }
  if (broken.length) {
    problems.push([
      `${plural(broken.length, 'import')} pointing at ${broken.length === 1 ? 'a file' : 'files'} that ${broken.length === 1 ? 'does' : 'do'} not exist:`,
      ...broken.map((line) => `    ${line}`),
      '  this one is broken online too.',
    ].join('\n'));
  }

  /* ---- Say what happened. ---- */

  if (problems.length) {
    console.error(`check-shell-assets: ${plural(problems.length, 'problem')} found.\n`);
    for (const problem of problems) console.error(`  ${problem}\n`);
    console.error('  SHELL_ASSETS is in sw.js. Bump CACHE_VERSION when you fix it, so the');
    console.error('  corrected list actually replaces the one already installed.');
    // Notes go out on this path too. A missing snapshot is worth knowing about
    // whether or not something else went wrong.
    for (const note of notes) console.error(`  note: ${note}`);
    process.exitCode = 1;
    return;
  }

  console.log(`check-shell-assets: ${plural(listed.length, 'asset')} precached, nothing has drifted.`);
  console.log(`  ${plural(modules.length, 'module')} under js/, ${plural(icons.length, 'icon')} in the manifest, all listed.`);
  console.log(`  ${plural(reachable.size, 'module')} reachable from ${pages.join(', ')}, all precached.`);
  console.log(`  ${plural(classic.size, 'classic script')} loaded by a page, all precached.`);
  for (const note of notes) console.log(`  note: ${note}`);
}

try {
  main();
} catch (err) {
  console.error(err.message);
  process.exitCode = 1;
}
